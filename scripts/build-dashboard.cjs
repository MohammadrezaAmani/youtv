/** Build a self-contained Cloudflare Dashboard Worker from the exact TypeScript runtime source. */
const ts=require('typescript');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const sourceDir=path.join(root,'apps/worker/src');
const files=['security.ts','hls.ts','cloudflare.ts','index.ts'];
const parts=files.map(filename=>{
  let code=ts.transpileModule(fs.readFileSync(path.join(sourceDir,filename),'utf8'),{
    compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,verbatimModuleSyntax:true}
  }).outputText;
  // All imports are module-local TypeScript imports between these four bundled files.
  code=code.replace(/^import\s+.+?\s+from\s+['"]\.\/[^'"]+['"];?\s*$/gm,'');
  if(filename!=='index.ts')code=code.replace(/^export\s+(?=(class|const|function|async|let)\b)/gm,'');
  code=code.replace(/^export\s*\{[^}]+\};?\s*$/gm,'');
  return `// ===== ${filename} =====\n${code}`;
});
const bundle='// Generated by scripts/build-dashboard.cjs. Edit apps/worker/src/*.ts, not this file.\n'+parts.join('\n\n');
const destination=path.join(root,'apps/worker/dashboard-worker.mjs');
fs.writeFileSync(destination,bundle);
console.log(`Created ${destination} (${bundle.length} bytes)`);
